cities = ['New York', 'San Francisco', 'Houston', 'Los Angeles']

# 💬 pop(2) remove o item da posição 2 ("Houston") e o DEVOLVE. Aqui o valor devolvido é descartado.
cities.pop(2)

print(cities)
